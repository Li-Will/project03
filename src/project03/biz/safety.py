"""高危事件前置判定（入口层安全闸）——「该转不转是事故」的第一道拦截。

为什么必须有（真实缺陷，2026-09-29 在容器冒烟时抓到）：
    评测里的 diagnose / escalate 用例**直接调 LangGraph**，所以 P1 规则在图内是被验证过的；
    但用户真正进来的是 `POST /api/v1/chat`，它先做意图分类 —— 「云盘里的照片好像被弄丢了，
    你们必须给个说法」不含故障词表里的任何词，被判成 FAQ，随后检索到 0.69 分的「隐私策略」
    就**直接回答**了。即：**入口层判定与图内判定不一致，P1 事件被 FAQ 直答吞掉**。
    这类缺陷评测集看不见（评测绕过了入口），但线上天天发生 —— 所以补一道前置闸。

设计取舍：
- 词表**故意窄**：只覆盖"一旦答错就是事故"的场景（数据丢失 / 账号资金安全 / 法务舆情），
  一般故障（"闪退""卡顿"）仍走 TICKET 诊断路径 —— 覆盖率不是目标，不误伤才是；
- 与 `prioritize_ticket` 的 P1 词表**分开**：后者的 "无法登录" 这类词用于工单定级合适，
  用于"禁止 FAQ 直答"就太激进（"登录失败怎么办"是标准 FAQ），所以不共用词表；
- 判定纯粹是规则、无 LLM：转人工决策必须确定、可审计、可回归。
"""
from __future__ import annotations

_HIGH_RISK_KW: tuple[str, ...] = (
    # 数据丢失 / 损坏（"找不到了"这类口语不算 —— 它同时是正常的找回咨询）
    "数据丢失", "文件丢了", "文件没了", "照片丢了", "照片没了", "资料丢了", "数据没了",
    "弄丢了", "全没了", "备份没了",
    # 账号 / 资金安全
    "账号被盗", "号被盗", "被盗", "盗号", "被盗刷", "被人登录", "账号被冻结", "账号被锁",
    "乱扣", "多扣", "重复扣款", "扣了两次", "被扣钱", "钱不见了", "钱被扣",
    # 法务 / 舆情升级
    "起诉", "律师函", "曝光你们", "找媒体",
)


def high_risk_reason(text: str) -> str | None:
    """命中高危事件 → 返回可审计的 reason；否则 None（继续正常意图路由）。"""
    t = (text or "").strip()
    if not t:
        return None
    hits = [k for k in _HIGH_RISK_KW if k in t]
    if not hits:
        return None
    return f"高危事件前置转人工（命中「{hits[0]}」：数据/账号/资金安全不得由 FAQ 直答）"